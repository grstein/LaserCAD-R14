//! Public-domain Hershey Simplex Roman glyph data for ASCII 32–126.
//!
//! ## Coordinate convention
//! - Y increases **downward** (screen convention; negated in [`super::layout`]).
//! - Baseline at `y = 0`.  Every alphanumeric glyph ends flush on it: no
//!   letter or digit reaches below `y = 0` except the five descenders.
//! - Capital, digit and ascender (`b d f h k l t`) tops at `y = −9`
//!   (9 units above the baseline — the cap height).
//! - Lowercase body (x-height) at `y = −6` **or** `y = −5`; both occur and the
//!   split is deliberate.  `a c e g o s` top at `−6`, `m n p q r u v w x y z`
//!   at `−5`.
//! - The `i` and `j` dots top at `y = −8`.
//! - Descenders (`g`, `j`, `p`, `q`, `y`) reach **exactly** `y = +4`, and all
//!   five bottom out at the same depth.
//! - Some punctuation legitimately crosses the baseline (commas, brackets,
//!   the underscore, `$`, the slashes, `@`).  The authoritative list is the
//!   `BASELINE_CROSSING_PUNCTUATION` const in the `vertical_metrics_contract`
//!   test in [`super::hershey`], which enforces everything above.
//!
//! ## Data format
//! Each entry is `(advance_width, strokes)`.  `advance_width` is the cursor
//! advance in Hershey units.  Each stroke is a `&[(i8, i8)]` pen-down path;
//! consecutive points form line segments.  A pen lift is represented by
//! starting a new stroke slice.
//!
//! ## Source
//! Adapted from the classic public-domain Hershey Simplex Roman font
//! (James O. Allen, US Navy, 1965; NIST distribution).
//!
//! LOC cap **exempt**: this file contains only data literals.

